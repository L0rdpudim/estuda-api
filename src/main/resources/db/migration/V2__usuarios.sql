-- Dados gerais da conta de cada usuário.
CREATE TABLE tb_usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ck_tb_usuario_nome_nao_vazio
        CHECK (LENGTH(BTRIM(nome)) > 0),
    CONSTRAINT ck_tb_usuario_email_nao_vazio
        CHECK (LENGTH(BTRIM(email)) > 0),
    CONSTRAINT ck_tb_usuario_senha_hash_nao_vazio
        CHECK (LENGTH(BTRIM(senha_hash)) > 0)
);

-- Cada usuário possui um único perfil, identificado pelo mesmo ID da conta.
CREATE TABLE tb_perfil_usuario (
    usuario_id BIGINT PRIMARY KEY,
    tipo_perfil VARCHAR(20) NOT NULL,
    status_validacao_professor VARCHAR(20),
    CONSTRAINT fk_tb_perfil_usuario_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES tb_usuario (id)
        ON DELETE CASCADE,
    CONSTRAINT ck_tb_perfil_usuario_tipo
        CHECK (tipo_perfil IN ('ESTUDANTE', 'PROFESSOR')),
    CONSTRAINT ck_tb_perfil_usuario_validacao
        CHECK (
            (tipo_perfil = 'ESTUDANTE' AND status_validacao_professor IS NULL)
            OR
            (tipo_perfil = 'PROFESSOR' AND status_validacao_professor IS NOT NULL
                AND status_validacao_professor IN (
                'PENDENTE', 'VALIDADO', 'REJEITADO'
            ))
        )
);

-- E-mails são únicos sem diferenciar letras maiúsculas de minúsculas.
CREATE UNIQUE INDEX uk_tb_usuario_email_ci
    ON tb_usuario (LOWER(email));