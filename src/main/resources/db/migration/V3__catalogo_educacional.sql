CREATE TABLE tb_etapa_ensino (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    ordem INTEGER NOT NULL,
    CONSTRAINT uk_tb_etapa_ensino_nome UNIQUE (nome),
    CONSTRAINT uk_tb_etapa_ensino_ordem UNIQUE (ordem),
    CONSTRAINT ck_tb_etapa_ensino_nome_nao_vazio
        CHECK (LENGTH(BTRIM(nome)) > 0),
    CONSTRAINT ck_tb_etapa_ensino_ordem_positiva
        CHECK (ordem > 0)
);

CREATE TABLE tb_ano_escolar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etapa_ensino_id BIGINT NOT NULL,
    nome VARCHAR(80) NOT NULL,
    ordem INTEGER NOT NULL,
    CONSTRAINT fk_tb_ano_escolar_etapa
        FOREIGN KEY (etapa_ensino_id)
        REFERENCES tb_etapa_ensino (id)
        ON DELETE CASCADE,
    CONSTRAINT uk_tb_ano_escolar_etapa_nome UNIQUE (etapa_ensino_id, nome),
    CONSTRAINT uk_tb_ano_escolar_etapa_ordem UNIQUE (etapa_ensino_id, ordem),
    CONSTRAINT ck_tb_ano_escolar_nome_nao_vazio
        CHECK (LENGTH(BTRIM(nome)) > 0),
    CONSTRAINT ck_tb_ano_escolar_ordem_positiva
        CHECK (ordem > 0)
);

CREATE TABLE tb_disciplina (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ano_escolar_id BIGINT NOT NULL,
    nome VARCHAR(120) NOT NULL,
    descricao TEXT,
    ordem INTEGER NOT NULL,
    CONSTRAINT fk_tb_disciplina_ano_escolar
        FOREIGN KEY (ano_escolar_id)
        REFERENCES tb_ano_escolar (id)
        ON DELETE CASCADE,
    CONSTRAINT uk_tb_disciplina_ano_nome UNIQUE (ano_escolar_id, nome),
    CONSTRAINT uk_tb_disciplina_ano_ordem UNIQUE (ano_escolar_id, ordem),
    CONSTRAINT ck_tb_disciplina_nome_nao_vazio
        CHECK (LENGTH(BTRIM(nome)) > 0),
    CONSTRAINT ck_tb_disciplina_ordem_positiva
        CHECK (ordem > 0)
);

CREATE TABLE tb_aula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_id BIGINT NOT NULL,
    titulo VARCHAR(200) NOT NULL,
    descricao TEXT,
    ordem INTEGER NOT NULL,
    CONSTRAINT fk_tb_aula_disciplina
        FOREIGN KEY (disciplina_id)
        REFERENCES tb_disciplina (id)
        ON DELETE CASCADE,
    CONSTRAINT uk_tb_aula_disciplina_ordem UNIQUE (disciplina_id, ordem),
    CONSTRAINT ck_tb_aula_titulo_nao_vazio
        CHECK (LENGTH(BTRIM(titulo)) > 0),
    CONSTRAINT ck_tb_aula_ordem_positiva
        CHECK (ordem > 0)
);

CREATE TABLE tb_material_didatico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aula_id BIGINT NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    titulo VARCHAR(200) NOT NULL,
    conteudo TEXT,
    url VARCHAR(2048),
    ordem INTEGER NOT NULL,
    CONSTRAINT fk_tb_material_didatico_aula
        FOREIGN KEY (aula_id)
        REFERENCES tb_aula (id)
        ON DELETE CASCADE,
    CONSTRAINT uk_tb_material_didatico_aula_ordem UNIQUE (aula_id, ordem),
    CONSTRAINT ck_tb_material_didatico_tipo
        CHECK (tipo IN ('TEXTO', 'VIDEO', 'REFERENCIA')),
    CONSTRAINT ck_tb_material_didatico_titulo_nao_vazio
        CHECK (LENGTH(BTRIM(titulo)) > 0),
    CONSTRAINT ck_tb_material_didatico_ordem_positiva
        CHECK (ordem > 0),
    CONSTRAINT ck_tb_material_didatico_conteudo
        CHECK (
            (tipo = 'TEXTO' AND conteudo IS NOT NULL
                AND LENGTH(BTRIM(conteudo)) > 0 AND url IS NULL)
            OR (tipo = 'VIDEO' AND url IS NOT NULL AND LENGTH(BTRIM(url)) > 0)
            OR (tipo = 'REFERENCIA' AND (
                (conteudo IS NOT NULL AND LENGTH(BTRIM(conteudo)) > 0)
                OR (url IS NOT NULL AND LENGTH(BTRIM(url)) > 0)
            ))
        )
);
